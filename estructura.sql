/* ----------------------------------------------------------------------------
   0. REINICIO
   Se borra todo para que el resultado no dependa de corridas anteriores.
   ---------------------------------------------------------------------------- */
DROP SCHEMA IF EXISTS staging CASCADE;
DROP TABLE  IF EXISTS public.pedidos   CASCADE;
DROP TABLE  IF EXISTS public.clientes  CASCADE;
DROP TABLE  IF EXISTS public.productos CASCADE;

CREATE SCHEMA staging;


/* ----------------------------------------------------------------------------
   1. TABLAS STAGING (datos crudos)
   Todas las columnas son TEXT a propósito: si se tiparan de entrada, la carga
   fallaría con la primera fecha "15/03/2025" o el primer precio "3,40".
   Primero se carga todo y después se limpia con reglas explícitas.
   ---------------------------------------------------------------------------- */
CREATE TABLE staging.productos (
    producto_id   TEXT,
    nombre        TEXT,
    categoria     TEXT,   -- llega con mayúsculas y espacios inconsistentes
    precio_lista  TEXT    -- llega con coma decimal, vacío, NULL o 'N/A'
);

CREATE TABLE staging.clientes (
    cliente_id    TEXT,
    razon_social  TEXT,
    tipo_cliente  TEXT,   -- variantes con y sin tilde / mayúsculas
    provincia     TEXT,   -- 'Bs As', 'Capital Federal', 'Cordoba', etc.
    email         TEXT,
    fecha_alta    TEXT
);

CREATE TABLE staging.pedidos (
    pedido_id       TEXT,  -- hay pedidos duplicados por reenvío de la integración
    cliente_id      TEXT,
    producto_id     TEXT,
    cantidad        TEXT,  -- algunos NULL o 0 (registros inválidos)
    precio_unitario TEXT,  -- algunos NULL o vacíos
    fecha_pedido    TEXT,  -- mezcla 'YYYY-MM-DD' y 'DD/MM/YYYY', y vacíos
    fecha_factura   TEXT,  -- siempre presente: sirve de respaldo para la fecha
    estado          TEXT   -- 'Entregado' / 'Cancelado' con formatos mezclados
);


