/* ----------------------------------------------------------------------------
   3. MODELO FINAL (esquema public) con tipos correctos
   - Importes en NUMERIC (nunca FLOAT): el dinero necesita precisión exacta.
   - Fechas en DATE: habilita DATE_TRUNC, EXTRACT y comparaciones de rango.
   - Las banderas *_imputado/a dejan trazabilidad de qué valores no son
     originales, para poder auditarlos o excluirlos en un análisis sensible.
   ---------------------------------------------------------------------------- */
CREATE TABLE public.productos (
    producto_id      INTEGER       PRIMARY KEY,
    nombre           VARCHAR(120)  NOT NULL,
    categoria        VARCHAR(40)   NOT NULL,
    precio_lista     NUMERIC(10,2) NOT NULL CHECK (precio_lista > 0),
    precio_imputado  BOOLEAN       NOT NULL DEFAULT FALSE
);

CREATE TABLE public.clientes (
    cliente_id     INTEGER       PRIMARY KEY,
    razon_social   VARCHAR(120)  NOT NULL,
    tipo_cliente   VARCHAR(30)   NOT NULL
                   CHECK (tipo_cliente IN ('Industria','Taller metalúrgico','Ferretería','Consumidor final')),
    provincia      VARCHAR(40)   NOT NULL,
    email          VARCHAR(120),            -- opcional: no se inventan emails
    fecha_alta     DATE          NOT NULL
);

CREATE TABLE public.pedidos (
    pedido_id        INTEGER       PRIMARY KEY,
    cliente_id       INTEGER       NOT NULL REFERENCES public.clientes(cliente_id),
    producto_id      INTEGER       NOT NULL REFERENCES public.productos(producto_id),
    cantidad         INTEGER       NOT NULL CHECK (cantidad > 0),
    precio_unitario  NUMERIC(10,2) NOT NULL CHECK (precio_unitario > 0),
    fecha_pedido     DATE          NOT NULL,
    fecha_factura    DATE          NOT NULL,
    estado           VARCHAR(15)   NOT NULL CHECK (estado IN ('Entregado','Cancelado')),
    -- importe calculado por el motor: evita que alguien lo guarde mal a mano
    monto_total      NUMERIC(12,2) GENERATED ALWAYS AS (cantidad * precio_unitario) STORED,
    precio_imputado  BOOLEAN       NOT NULL DEFAULT FALSE,
    fecha_imputada   BOOLEAN       NOT NULL DEFAULT FALSE
);


/* ----------------------------------------------------------------------------
   4. LIMPIEZA Y TRANSFORMACIÓN  (staging -> public)
   ---------------------------------------------------------------------------- */

-- 4.1 PRODUCTOS
-- Reglas:
--  * Categoría: TRIM + primera letra mayúscula y resto minúscula, para que
--    'DISCOS DE CORTE' y '  discos de corte ' cuenten como la misma categoría
--    (si no, el GROUP BY las separaría y partiría las ventas en tres).
--  * Precio: 'N/A' y '' pasan a NULL con NULLIF; la coma decimal se reemplaza
--    por punto antes de convertir a NUMERIC.
--  * Precio faltante (COALESCE en cascada):
--      1° el MÁXIMO precio cobrado en pedidos de ese producto: los descuentos
--         solo bajan el precio, así que el máximo es la mejor aproximación al
--         precio de lista (lo pagan los consumidores finales, sin descuento).
--      2° si el producto no tiene ventas, el precio promedio de su categoría.
WITH precio_txt AS (
    SELECT TRIM(producto_id)::INTEGER                                       AS producto_id,
           TRIM(nombre)                                                     AS nombre,
           UPPER(LEFT(TRIM(categoria), 1)) || LOWER(SUBSTRING(TRIM(categoria) FROM 2)) AS categoria,
           REPLACE(NULLIF(NULLIF(TRIM(precio_lista), ''), 'N/A'), ',', '.')::NUMERIC(10,2) AS precio
    FROM   staging.productos
),
max_cobrado AS (
    SELECT TRIM(producto_id)::INTEGER                             AS producto_id,
           MAX(NULLIF(TRIM(precio_unitario), '')::NUMERIC(10,2))  AS precio_max
    FROM   staging.pedidos
    GROUP  BY 1
),
prom_categoria AS (
    SELECT categoria, ROUND(AVG(precio), 2) AS precio_prom
    FROM   precio_txt
    GROUP  BY categoria
)
INSERT INTO public.productos (producto_id, nombre, categoria, precio_lista, precio_imputado)
SELECT p.producto_id,
       p.nombre,
       p.categoria,
       COALESCE(p.precio, m.precio_max, c.precio_prom),
       (p.precio IS NULL)
FROM   precio_txt p
LEFT   JOIN max_cobrado    m ON m.producto_id = p.producto_id
LEFT   JOIN prom_categoria c ON c.categoria   = p.categoria;


-- 4.2 CLIENTES
-- Reglas:
--  * Duplicados exactos: DISTINCT ON (cliente_id) conserva una sola fila.
--  * Razón social: TRIM; si llegó toda en mayúsculas se pasa a formato título
--    (INITCAP) y se restauran las siglas societarias SRL / SA / SAS.
--  * Tipo de cliente y provincia: se normaliza la clave (minúsculas, sin
--    tildes ni puntos) y un CASE la mapea a una única etiqueta oficial.
--  * Email: '' -> NULL. No es una columna crítica para el análisis y no se
--    imputa: inventar un email sería peor que dejarlo vacío.
WITH base AS (
    SELECT DISTINCT ON (TRIM(cliente_id))
           TRIM(cliente_id)::INTEGER AS cliente_id,
           TRIM(razon_social)        AS razon_social,
           TRANSLATE(LOWER(TRIM(tipo_cliente)), 'áéíóúü', 'aeiouu')     AS tipo_key,
           TRANSLATE(LOWER(TRIM(provincia)),    'áéíóúü.', 'aeiouu')    AS prov_key,
           NULLIF(TRIM(email), '')   AS email,
           fecha_alta::DATE          AS fecha_alta
    FROM   staging.clientes
    ORDER  BY TRIM(cliente_id)
)
INSERT INTO public.clientes (cliente_id, razon_social, tipo_cliente, provincia, email, fecha_alta)
SELECT cliente_id,
       CASE
           WHEN razon_social = UPPER(razon_social) THEN
               REGEXP_REPLACE(REGEXP_REPLACE(REGEXP_REPLACE(INITCAP(razon_social),
                   '\mSrl\M', 'SRL', 'g'), '\mSas\M', 'SAS', 'g'), '\mSa\M', 'SA', 'g')
           ELSE razon_social
       END,
       CASE tipo_key
           WHEN 'industria'          THEN 'Industria'
           WHEN 'taller metalurgico' THEN 'Taller metalúrgico'
           WHEN 'ferreteria'         THEN 'Ferretería'
           WHEN 'consumidor final'   THEN 'Consumidor final'
       END,
       CASE
           WHEN prov_key IN ('buenos aires', 'bs as')        THEN 'Buenos Aires'
           WHEN prov_key IN ('caba', 'capital federal')      THEN 'CABA'
           WHEN prov_key = 'cordoba'                         THEN 'Córdoba'
           WHEN prov_key = 'santa fe'                        THEN 'Santa Fe'
           WHEN prov_key = 'entre rios'                      THEN 'Entre Ríos'
           WHEN prov_key = 'neuquen'                         THEN 'Neuquén'
           WHEN prov_key = 'tucuman'                         THEN 'Tucumán'
           WHEN prov_key = 'mendoza'                         THEN 'Mendoza'
           ELSE INITCAP(prov_key)   -- provincia nueva: se conserva en formato título
       END,
       email,
       fecha_alta
FROM   base;


-- 4.3 PEDIDOS
-- Reglas:
--  * Duplicados: DISTINCT ON (pedido_id) elimina los reenvíos de la integración
--    (si no, esos pedidos sumarían el doble en todas las métricas).
--  * Fecha: CASE según el patrón del texto ('YYYY-MM-DD' o 'DD/MM/YYYY').
--    Si falta, COALESCE con la fecha de factura: se emite 0 a 3 días después
--    del pedido, así que el error es menor a una semana y no cambia el mes en
--    la gran mayoría de los casos. Queda marcado en fecha_imputada.
--  * Precio unitario faltante (COALESCE en cascada):
--      1° precio promedio que pagó ese MISMO TIPO de cliente por ese producto
--         (respeta el descuento real del segmento: una ferretería no paga
--         lo mismo que un consumidor final),
--      2° precio de lista del producto.
--  * Cantidad NULL o 0: el registro no representa una venta real y se descarta
--    (no se puede imputar cuántas unidades se vendieron). En analisis.sql se
--    cuantifica cuántas filas se excluyeron por cada motivo.
--  * Estado: TRIM + INITCAP unifica 'CANCELADO', 'entregado ', etc.
WITH dedup AS (
    SELECT DISTINCT ON (TRIM(pedido_id)) *
    FROM   staging.pedidos
    ORDER  BY TRIM(pedido_id)
),
tipado AS (
    SELECT TRIM(d.pedido_id)::INTEGER                        AS pedido_id,
           TRIM(d.cliente_id)::INTEGER                       AS cliente_id,
           TRIM(d.producto_id)::INTEGER                      AS producto_id,
           NULLIF(TRIM(d.cantidad), '')::INTEGER             AS cantidad,
           NULLIF(TRIM(d.precio_unitario), '')::NUMERIC(10,2) AS precio_unitario,
           CASE
               WHEN TRIM(d.fecha_pedido) ~ '^\d{4}-\d{2}-\d{2}$' THEN TRIM(d.fecha_pedido)::DATE
               WHEN TRIM(d.fecha_pedido) ~ '^\d{2}/\d{2}/\d{4}$' THEN TO_DATE(TRIM(d.fecha_pedido), 'DD/MM/YYYY')
           END                                                AS fecha_pedido,
           TRIM(d.fecha_factura)::DATE                        AS fecha_factura,
           INITCAP(TRIM(d.estado))                            AS estado
    FROM   dedup d
),
precio_segmento AS (
    -- precio promedio pagado por tipo de cliente y producto (solo precios reales)
    SELECT c.tipo_cliente, t.producto_id, ROUND(AVG(t.precio_unitario), 2) AS precio_prom
    FROM   tipado t
    JOIN   public.clientes c ON c.cliente_id = t.cliente_id
    WHERE  t.precio_unitario IS NOT NULL
    GROUP  BY c.tipo_cliente, t.producto_id
)
INSERT INTO public.pedidos (pedido_id, cliente_id, producto_id, cantidad, precio_unitario,
                            fecha_pedido, fecha_factura, estado, precio_imputado, fecha_imputada)
SELECT t.pedido_id,
       t.cliente_id,
       t.producto_id,
       t.cantidad,
       COALESCE(t.precio_unitario, ps.precio_prom, p.precio_lista),
       COALESCE(t.fecha_pedido, t.fecha_factura),
       t.fecha_factura,
       t.estado,
       (t.precio_unitario IS NULL),
       (t.fecha_pedido   IS NULL)
FROM   tipado t
JOIN   public.clientes  c  ON c.cliente_id  = t.cliente_id
JOIN   public.productos p  ON p.producto_id = t.producto_id
LEFT   JOIN precio_segmento ps ON ps.tipo_cliente = c.tipo_cliente
                              AND ps.producto_id  = t.producto_id
WHERE  t.cantidad > 0;     -- descarta cantidad NULL o 0 (NULL > 0 no es verdadero)


/* ----------------------------------------------------------------------------
   5. ÍNDICES
   Solo en las columnas que el análisis usa en JOIN y en filtros de fecha.
   Las PK ya tienen su índice B-Tree automático. No se indexa todo: cada
