   ---------------------------------------------------------------------------- */
CREATE INDEX idx_pedidos_cliente  ON public.pedidos (cliente_id);    -- JOIN con clientes
CREATE INDEX idx_pedidos_producto ON public.pedidos (producto_id);   -- JOIN con productos
CREATE INDEX idx_pedidos_fecha    ON public.pedidos (fecha_pedido);  -- análisis por mes / rangos

